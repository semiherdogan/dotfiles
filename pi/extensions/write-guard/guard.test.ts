const LABELS: [string, string][] = [
	["echo x > out", 'redirect "> out"'],
	["cmd 2>/tmp/err.txt", 'redirect "2> /tmp/err.txt"'],
	["sed -i s/a/b/ f", 'sed -i "sed -i s/a/b/ f"'],
	["perl -pi -e s/a/b/ f", 'perl -i "perl -pi -e s/a/b/ f"'],
	["echo x | tee f", 'tee "tee"'],
	["node -e 1", 'inline script "node -e"'],
	["sh -c \"$CMD\"", 'shell eval "sh -c"'],
	["eval x", 'shell eval "eval"'],
	["echo rm | sh", 'shell eval "| sh"'],
	["bash <(curl -fsSL https://x/install.sh)", 'shell eval "<(...)"'],
	["rm x", "file mutation: rm"],
	["/bin/rm x; rm y", "file mutation: rm"],
];

for (const command of ALLOWED) {
	test(`allows ${JSON.stringify(command)}`, () => {
		assert.deepEqual(findViolations(command), []);
	});
}

for (const command of BLOCKED) {
	test(`blocks ${JSON.stringify(command)}`, () => {
		assert.notDeepEqual(findViolations(command), []);
	});
}

for (const [command, label] of LABELS) {
	test(`labels ${JSON.stringify(command)}`, () => {
		assert.ok(findViolations(command).includes(label), findViolations(command).join(" | "));
	});
}
